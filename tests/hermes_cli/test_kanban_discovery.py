"""Tests for the T5/P4 discovery-report card convention (design §8.2).

Pins the exact frontmatter key + level vocabulary, the standardized DISCOVERY
SUMMARY section and its five EXACT field names, tolerant parse/validate,
declaration-driven classification, and the backward-compatibility contract:
cards that do not declare `discovery:` are generated byte-identically.

The convention itself lives in ``hermes_cli.kanban_discovery``; this suite also
covers its wiring into the two card templates (``kanban_specify`` /
``kanban_decompose``) so the declaration cannot drift from the generator.
"""

from __future__ import annotations

import json as jsonlib
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

from hermes_cli import kanban_db as kb
from hermes_cli import kanban_db_connect as kbc
from hermes_cli import kanban_decompose as decomp
from hermes_cli import kanban_discovery as disc
from hermes_cli import kanban_specify as spec

EXACT_FIELDS = ["finding", "confidence", "impact-lane", "suggested-action", "affected-card-ids"]
EXACT_LEVELS = ["flag-med", "flag-high"]


@pytest.fixture
def kanban_home(tmp_path, monkeypatch):
    home = tmp_path / ".hermes"
    home.mkdir()
    monkeypatch.setenv("HERMES_HOME", str(home))
    monkeypatch.setattr(Path, "home", lambda: tmp_path)
    kb.init_db()
    return home


def _patch_aux_client(content: str):
    resp = MagicMock()
    resp.choices = [MagicMock()]
    resp.choices[0].message.content = content
    return patch("agent.auxiliary_client.call_llm", return_value=resp)


def _patch_profiles(names: list[str]):
    from types import SimpleNamespace

    fakes = [
        SimpleNamespace(
            name=n, is_default=(i == 0), description=f"desc for {n}",
            description_auto=False, model="m", provider="p", skill_count=1,
        )
        for i, n in enumerate(names)
    ]
    return [
        patch("hermes_cli.profiles.list_profiles", return_value=fakes),
        patch("hermes_cli.profiles.profile_exists", side_effect=lambda x: x in names),
        patch("hermes_cli.profiles.get_active_profile_name", return_value=names[0]),
    ]


def _decompose(tid: str, payload: str, names: list[str]):
    patchers = _patch_profiles(names)
    for p in patchers:
        p.start()
    try:
        with _patch_aux_client(payload), patch(
            "hermes_cli.kanban_decompose._load_config", return_value={},
        ):
            return decomp.decompose_task(tid, author="t")
    finally:
        for p in patchers:
            p.stop()


