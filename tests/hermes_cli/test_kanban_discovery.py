def test_decomposer_prompt_renders_the_block_from_the_module():
    assert disc.discovery_prompt_block() in decomp._SYSTEM_PROMPT


def test_decompose_gives_a_declared_child_the_section_only(kanban_home):
    with kbc.connect() as conn:
        tid = kb.create_task(conn, title="quest", triage=True)
    payload = jsonlib.dumps({
        "fanout": True, "rationale": "x",
        "tasks": [
            {"title": "Report a finding", "body": "discovery: flag-high\n\n**Goal**\nreport",
             "assignee": None, "parents": []},
            {"title": "Implement the fix", "body": "**Goal**\ncode it",
             "assignee": None, "parents": [0]},
        ],
    })
    outcome = _decompose(tid, payload, ["default"])
    assert outcome.ok, outcome.reason
    with kbc.connect() as conn:
        kids = [kb.get_task(conn, cid) for cid in (outcome.child_ids or [])]
    declared = next(k for k in kids if "Report" in k.title)
    plain = next(k for k in kids if "Implement" in k.title)
    assert disc.has_section(declared.body)
    assert disc.missing_section_fields(declared.body) == []
    assert "discovery:" not in (plain.body or "")
    # The C2.3 bucket headings survive the insertion, after the section.
    assert "Adoption:" in declared.body


def test_decompose_single_path_carries_the_section(kanban_home):
    with kbc.connect() as conn:
        tid = kb.create_task(conn, title="quest2", triage=True)
