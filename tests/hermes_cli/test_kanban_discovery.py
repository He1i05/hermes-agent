def test_frontmatter_key_and_levels_are_exact():
    assert disc.DISCOVERY_FIELD == "discovery"
    assert list(disc.DISCOVERY_LEVELS) == EXACT_LEVELS


def test_section_heading_and_field_names_are_exact():
    assert disc.DISCOVERY_SECTION_HEADING == "DISCOVERY SUMMARY"
    assert list(disc.DISCOVERY_SECTION_FIELDS) == EXACT_FIELDS


def test_suggested_action_vocabulary_is_exact():
    assert list(disc.DISCOVERY_ACTIONS) == ["continue", "refine", "pivot"]


