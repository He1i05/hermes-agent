# ---------- render ----------


def test_render_frontmatter_emits_the_exact_key():
    assert disc.render_frontmatter("flag-high") == "discovery: flag-high"
    assert disc.render_frontmatter("flag-med") == "discovery: flag-med"


def test_render_frontmatter_marker_when_level_invalid():
    """An unfilled declaration stays visibly a CHOICE, never a silent default."""
    assert disc.render_frontmatter("bogus") == "discovery: flag-med | flag-high"
    assert disc.render_frontmatter(None) == "discovery: flag-med | flag-high"


def test_render_section_emits_bold_heading_and_all_five_fields():
    section = disc.render_section()
    assert disc.DISCOVERY_SECTION_HEADING in section
    lines = [l for l in section.splitlines() if l.startswith("- ")]
    assert [l[2:].split(":")[0] for l in lines] == EXACT_FIELDS


def test_render_section_keeps_filled_values_verbatim():
    section = disc.render_section(
        finding="X invalidates Y", confidence="high", impact_lane="implementation",
        suggested_action="pivot", affected_card_ids="t_aaa, t_bbb",
    )
    for value in ("X invalidates Y", "high", "implementation", "pivot", "t_aaa, t_bbb"):
        assert value in section


# ---------- parsing / validation ----------


def test_parse_section_reads_all_five():
    text = "**DISCOVERY SUMMARY**\n- finding: f\n- confidence: c\n- impact-lane: l\n" \
           "- suggested-action: pivot\n- affected-card-ids: t_1"
    assert set(disc.parse_section(text)) == set(EXACT_FIELDS)


def test_parse_section_ignores_unrelated_and_empty_input():
    assert disc.parse_section("**Goal**\nDo it.") == {}
    for junk in (None, "", 7, ["x"]):
        assert disc.parse_section(junk) == {}


def test_has_section_requires_heading_and_all_five():
    assert disc.has_section(disc.render_section()) is True
    assert disc.has_section("**DISCOVERY SUMMARY**\n- finding: f") is False


def test_missing_section_fields_in_canonical_order():
    assert disc.missing_section_fields("- finding: f") == EXACT_FIELDS[1:]
    assert disc.missing_section_fields(disc.render_section()) == []


def test_validate_flags_missing_heading_and_fields():
    problems = disc.validate_discovery_card("discovery: flag-high\n\n**Goal** x")
    assert any("section heading" in p for p in problems)
    assert sum(p.startswith("missing field") for p in problems) == len(EXACT_FIELDS)


def test_validate_flags_unfilled_placeholders():
    problems = disc.validate_discovery_card(
        "discovery: flag-high\n" + disc.render_section(),
    )
    assert any("placeholder" in p for p in problems)


def test_validate_accepts_a_complete_report():
    body = disc.ensure_discovery_section(
        "phase: research\ndiscovery: flag-high\n\n**Goal** x", level="flag-high",
        finding="f", confidence="high", impact_lane="implementation",
        suggested_action="pivot", affected_card_ids="t_1",
    )
    assert disc.validate_discovery_card(body) == []


def test_validate_flags_out_of_vocabulary_suggested_action():
    body = disc.ensure_discovery_section(
        "discovery: flag-high\n\n**Goal** x", level="flag-high",
        finding="f", confidence="high", impact_lane="x",
        suggested_action="explode", affected_card_ids="none",
    )
    assert any("suggested-action" in p for p in disc.validate_discovery_card(body))


def test_validate_never_raises_on_junk():
    for junk in (None, 7, ["x"], "discovery: flag-high"):
        assert isinstance(disc.validate_discovery_card(junk), list)


# ---------- declaration-driven classification ----------


def test_a_valid_declaration_makes_a_discovery_card():
    assert disc.is_discovery_card(body="discovery: flag-high") is True
    assert disc.is_discovery_card(body="phase: research\ndiscovery: flag-med") is True


def test_undeclared_cards_are_not_discovery_cards():
    """The whole point: reading like a report is NOT a declaration."""
    assert disc.is_discovery_card(
        body="phase: research\n**DISCOVERY SUMMARY**\n- finding: x",
    ) is False
    assert disc.is_discovery_card("Survey the landscape", "phase: research\n**Goal** x") is False
    assert disc.is_discovery_card() is False


def test_an_invalid_level_is_not_a_declaration():
    assert disc.is_discovery_card(body="discovery: flag-catastrophic") is False


# ---------- ensure_discovery_section ----------


def test_ensure_inserts_declaration_after_phase_line():
    out = disc.ensure_discovery_section(
        "phase: research\n\n**Goal** survey", level="flag-high",
    )
    lines = out.splitlines()
    assert lines[0] == "phase: research"
    assert lines[1] == "discovery: flag-high"
    assert "**Goal** survey" in out


def test_ensure_prepends_when_no_phase_line():
    out = disc.ensure_discovery_section("**Goal** x", level="flag-med")
    assert out.startswith("discovery: flag-med\n")


def test_ensure_completes_a_partial_section_and_keeps_filled_values():
    partial = "discovery: flag-high\n\n**Goal** x\n\n" + disc.render_section(finding="only this")
    out = disc.ensure_discovery_section(partial)
    assert disc.missing_section_fields(out) == []
    assert disc.parse_section(out)["finding"] == "only this"


def test_ensure_keeps_every_caller_supplied_value():
    """Regression: hyphenated field names must not be dropped at the call site.

    The section renders `impact-lane` / `suggested-action` / `affected-card-ids`
    but the kwargs are underscored — a lookup under only one spelling silently
    replaced the caller's value with its placeholder.
    """
    out = disc.ensure_discovery_section(
        "discovery: flag-high\n\n**Goal** x", level="flag-high",
        finding="f", confidence="c", impact_lane="implementation",
        suggested_action="pivot", affected_card_ids="t_aaa, t_bbb",
    )
    found = disc.parse_section(out)
    assert found == {
        "finding": "f", "confidence": "c", "impact-lane": "implementation",
        "suggested-action": "pivot", "affected-card-ids": "t_aaa, t_bbb",
    }
    assert disc.validate_discovery_card(out) == []


def test_ensure_is_idempotent_and_declares_once():
    once = disc.ensure_discovery_section(
        "phase: research\n\n**Goal** survey", level="flag-high", finding="f",
    )
    assert disc.ensure_discovery_section(once) == once
    assert disc.ensure_discovery_section(disc.ensure_discovery_section(once)) == once
    assert once.count("discovery:") == 1
    assert len(disc._HEADING_RE.findall(once)) == 1


def test_ensure_leaves_an_undeclared_body_byte_identical():
    """Backward compatibility: no declaration means no injection, ever."""
    base = "phase: research\n\n**Goal** survey things"
    assert disc.ensure_discovery_section(base) == base
    assert disc.ensure_discovery_section(base, level="flag-catastrophic") == base
    assert disc.ensure_discovery_section("") == ""
    assert disc.ensure_discovery_section(None) == ""


